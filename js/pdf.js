  // копия описания документа: pdfmake дописывает в узлы служебные поля, повторно отдавать тот же объект нельзя
  function cloneDD(v) {
    if (Array.isArray(v)) return v.map(cloneDD);
    if (!v || typeof v !== 'object') return v;
    const o = {};
    Object.keys(v).forEach(k => { if (k[0] !== '_') o[k] = k === 'layout' ? v[k] : cloneDD(v[k]); });
    return o;
  }
  // уменьшить шрифты и вертикальные отступы в k раз
  function scaleDD(dd, k) {
    const walk = v => {
      if (Array.isArray(v)) { v.forEach(walk); return; }
      if (!v || typeof v !== 'object') return;
      if (typeof v.fontSize === 'number') v.fontSize = +(v.fontSize * k).toFixed(2);
      if (Array.isArray(v.margin)) v.margin = v.margin.map((m, i) => i % 2 ? +(m * k).toFixed(1) : m);
      Object.keys(v).forEach(key => { if (key !== 'layout' && key !== 'margin') walk(v[key]); });
    };
    walk(dd.content);
    dd.defaultStyle = Object.assign({}, dd.defaultStyle, { fontSize: +((dd.defaultStyle.fontSize || 9.5) * k).toFixed(2), lineHeight: 1 });
    dd.pageMargins = dd.pageMargins.map((m, i) => i % 2 ? Math.max(14, Math.round(m * k)) : m);
    return dd;
  }
  // число страниц: pdfmake сообщает его в колонтитул
  function pageCount(dd) {
    return new Promise((resolve, reject) => {
      let total = 0;
      const d = Object.assign({}, dd, { footer: (c, t) => { total = t; return dd.footer ? dd.footer(c, t) : null; } });
      try { pdfMake.createPdf(d).getBuffer(() => resolve(total)); } catch (e) { reject(e); }
    });
  }
  async function toBlob(dd) {
    setup();
    // КС и смета: если вылезли на второй лист совсем немного — ужимаем до одной страницы (не мельче 78 %);
    // длинный документ, который так не помещается, остаётся многостраничным в обычном размере
    if (dd.fitOnePage) {
      const base = cloneDD(dd);
      if (await pageCount(cloneDD(base)) === 2) {
        for (const k of [0.94, 0.88, 0.83, 0.78]) {
          const t = scaleDD(cloneDD(base), k);
          if (await pageCount(cloneDD(t)) === 1) { dd = t; break; }
        }
      }
    }
    // акты: каждый подгоняется отдельно — короткий акт не мельчает из-за длинного соседа в пакете
    // части: акты пакета, разделы ОЖР (у титула своя ориентация листа), целиком реестр / ЖВК
    if (dd.fitParts) {
      const base = cloneDD(Object.assign({}, dd, { content: [], fitParts: undefined }));
      const font = (base.defaultStyle && base.defaultStyle.fontSize) || 9.5;
      const parts = dd.fitParts.map(x => Array.isArray(x) ? { content: x } : x);
      // разрыв страницы в начале части ставим на обёртку, иначе пробный документ начнётся с пустого листа
      const clean = c => { const a = cloneDD(c); if (a[0] && typeof a[0] === 'object') { delete a[0].pageBreak; delete a[0].pageOrientation; } return a; };
      const part = (c, k) => k === 1 ? { stack: clean(c) } : { stack: scaleDD({ content: clean(c), defaultStyle: {}, pageMargins: [] }, k).content, fontSize: +(font * k).toFixed(2), lineHeight: 1 };
      const test = (x, node) => pageCount(Object.assign(cloneDD(base), { content: [cloneDD(node)], pageOrientation: x.orientation || base.pageOrientation }));
      const fitted = [];
      for (const x of parts) {
        // документ на 2 листа и больше: если последний лист почти пустой — убираем его (минус одна страница)
        let best = part(x.content, 1);
        const n = await test(x, best);
        if (n >= 2) {
          for (const k of [0.94, 0.88, 0.83, 0.78]) {
            const t = part(x.content, k);
            if (await test(x, t) < n) { best = t; break; }
          }
        }
        fitted.push(best);
      }
      fitted.forEach((f, i) => {
        if (i > 0) f.pageBreak = 'before';
        if (i > 0 && parts[i].orientation) f.pageOrientation = parts[i].orientation;
      });
      dd = Object.assign(cloneDD(base), { content: fitted, pageOrientation: parts[0].orientation || base.pageOrientation });
    }
    return new Promise((resolve, reject) => {
      try { pdfMake.createPdf(dd).getBlob(resolve); } catch (e) { reject(e); }
    });
  }

