      lbl(no + ' Даты:'),
      { table: { widths: [20, 80, 8, 18, 8, 80, 30, 12, '*'], body: [row('начала работ', start), row('окончания работ', end)] }, layout: UL, margin: [0, 1, 0, 2] }
