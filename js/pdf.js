    out.push(lbl(T.builderLabel));
    out.push(val(C.orgLine(P.builder)), cap(T.orgCapA + ','));
    out.push(val(C.sroLine(P.builder)), cap(T.sroBuild));
    out.push(lbl(T.designerLabel));
    out.push(val(C.orgLine(P.designer)), cap(T.orgCapA + ','));
    out.push(val(C.sroLine(P.designer)), cap(T.sroDes));

    out.push({ text: F.title[0], bold: true, alignment: 'center', fontSize: 12, margin: [0, 8, 0, 0], _g: 1 });
    F.title.slice(1).forEach(t => out.push({ text: t, bold: true, alignment: 'center', margin: [40, 0, 40, 0] }));
    out.push(dateLine(v.number, v.date));

    out.push(lbl(T.r1));
    out.push(val(C.personActLine(rCust)), cap(T.r1cap));
    out.push(val(custRepOrg), cap(F.r1cap2));
    out.push(lbl(T.r2), val(C.personActLine(rBuild)), cap(T.r2cap));
