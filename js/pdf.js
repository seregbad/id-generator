  // ---------- общий конструктор документа ----------
  function doc(content, opts) {
    opts = opts || {};
    const d = {
      pageSize: 'A4',
      pageOrientation: opts.landscape ? 'landscape' : 'portrait',
      pageMargins: opts.margins || [48, 28, 28, 30],
      content,
      defaultStyle: { font: 'Tinos', fontSize: opts.fontSize || 9.5, lineHeight: 1.05 },
      info: { title: opts.title || 'Документ', creator: 'Генератор ИД' }
    };
    if (opts.fit) d.fitOnePage = true;
    if (opts.pageNumbers) {
      d.footer =(cur, total) => ({ text: 'стр. ' + cur + ' из ' + total, alignment: 'right', fontSize: 7, margin: [0, 8, 28, 0] });
    }
    return d;
  }

  // акт, чуть вылезающий на второй лист, ужимается до одного (каждый акт — отдельно, см. toBlob)
  const fitActs = p => p.settings.fitActs !== false;
  function actDoc(p, a) {
    const v = C.actView(p, a);
    const c = actContent(p, a);
    const d = doc(c, { title: a.type + ' № ' + v.number });
    if (fitActs(p)) d.fitParts = [c];
    return d;
  }
  // несколько актов одним файлом
  function actsDoc(p, acts) {
    const parts = acts.map(a => actContent(p, a));
    const content = [];
    parts.forEach((c, i) => content.push({ stack: c, pageBreak: i > 0 ? 'before' : undefined }));
    const d = doc(content, { title: 'Акты' });
    if (fitActs(p)) d.fitParts = parts;
    return d;
  }

