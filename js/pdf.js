    out.push(lbl(F.r5), val(C.personOrgLine(p, rExec)), cap(F.r5cap));

    const body = BODY[a.type](p, a, v, P, execOrg);
    out.push(...body);

    out.push(lbl('Дополнительные сведения', { margin: [0, 4, 0, 0] }));
    if (a.type !== 'Разбивка осей') out.push(val(a.extra));
    else out.push(val(''));
