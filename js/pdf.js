  function groups(items) {
    const out = []; let cur = null;
    items.forEach(it => {
      if (!it) return;
      if (it._g || !cur) { cur = { stack: [], unbreakable: true }; out.push(cur); }
      cur.stack.push(it);
    });
    return out;
  }
